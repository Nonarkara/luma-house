export function detectLang(): Lang {
  try {
    const saved = localStorage.getItem(STORAGE_KEY)
    if (saved === 'en' || saved === 'th' || saved === 'zh') return saved
  } catch { /* private mode */ }
  if (typeof navigator === 'undefined') return 'en'
  const nav = navigator.language.toLowerCase()
  if (nav.startsWith('th')) return 'th'
  if (nav.startsWith('zh')) return 'zh'
  return 'en'
}

export function persistLang(lang: Lang): void {
  try { localStorage.setItem(STORAGE_KEY, lang) } catch { /* private mode */ }
  if (typeof document !== 'undefined') document.documentElement.lang = lang === 'zh' ? 'zh-Hans' : lang
}

export function translate(lang: Lang, text: string): string {
  if (lang === 'en' || text === '') return text
  const exact = TABLE.get(text)
  if (exact) return exact[lang]
  for (const pattern of PATTERNS) {
    const match = text.match(pattern.re)
    if (match) return pattern[lang](match)
  }
  return text
}

export function htmlLang(lang: Lang): string {
  return lang === 'zh' ? 'zh-Hans' : lang
}
